import {readFile, writeFile} from "node:fs/promises";
import openapiTS, {astToString} from "openapi-typescript";
import ts from "typescript";

const [input, output] = process.argv.slice(2);
if (!input || !output) throw new TypeError("usage: generate-openapi-types.mjs INPUT OUTPUT");

const schema = await readFile(input, "utf8");
const nodes = await openapiTS(schema, {
  transform(value) {
    if ((value.type === "integer" || Array.isArray(value.type) && value.type.includes("integer")) && value.format === "uint64") {
      const bigint = ts.factory.createKeywordTypeNode(ts.SyntaxKind.BigIntKeyword);
      return Array.isArray(value.type) && value.type.includes("null")
        ? ts.factory.createUnionTypeNode([bigint, ts.factory.createLiteralTypeNode(ts.factory.createNull())])
        : bigint;
    }
  },
});
await writeFile(output, `/**\n * This file was auto-generated by openapi-typescript.\n * uint64 wire integers are bigint because the Admin UI decodes JSON losslessly.\n * Do not make direct changes to the file.\n */\n\n${astToString(nodes)}`, "utf8");
